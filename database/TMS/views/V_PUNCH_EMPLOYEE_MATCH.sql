
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "TMS"."V_PUNCH_EMPLOYEE_MATCH" ("SOURCE_ID", "SOURCE_USER_ID", "EMPLOYEE_ID", "TK", "SOURCE_TIMESTAMP", "DEVICE_NAME") AS
  select p.SOURCE_ID, p.SOURCE_USER_ID, e.ID as EMPLOYEE_ID,
       p.TK, p.SOURCE_TIMESTAMP, p.DEVICE_NAME
  from V_SOURCE_PUNCH_RECENT p
  join EMPLOYEE e on to_char(e.EMPLOYEE_NUMBER) = p.SOURCE_USER_ID
 where AUTH_PKG.can_access_location_sql(e.LOCATION_ID) = 1;
