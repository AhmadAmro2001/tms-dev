
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "TMS"."V_TRANSACTION" ("ID", "EMPLOYEE_ID", "TYPE", "DATE", "DEVICE_ID", "DEVICE_NAME", "CREATED_BY", "CREATION_DATE", "LAST_UPDATED_BY", "LAST_UPDATE_DATE") AS
  select ID, EMPLOYEE_ID, TYPE, "DATE", DEVICE_ID, DEVICE_NAME,
       CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
from "TRANSACTION";
