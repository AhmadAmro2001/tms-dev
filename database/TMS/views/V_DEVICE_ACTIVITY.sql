
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "TMS"."V_DEVICE_ACTIVITY" ("DEVICE_ID", "DEVICE_NAME", "LOCATION_ID", "LAST_DOWNLOADED", "LAST_TRANSACTION", "IS_PENDING_REQUEST", "HAS_LAST_REQUEST_FAILED") AS
  select d.ID as DEVICE_ID,
       d.NAME as DEVICE_NAME,
       d.LOCATION_ID,
       d.LAST_DOWNLOADED,
       d.LAST_TRANSACTION,
       d.IS_PENDING_REQUEST,
       d.HAS_LAST_REQUEST_FAILED
from DEVICE d;
