
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "TMS"."V_UNMATCHED_PUNCH" ("SOURCE_ID", "SOURCE_USER_ID", "TK", "SOURCE_TIMESTAMP", "DEVICE_NAME") AS
  select p.SOURCE_ID, p.SOURCE_USER_ID, p.TK,
       p.SOURCE_TIMESTAMP, p.DEVICE_NAME
 from V_SOURCE_PUNCH_RECENT p
  left join EMPLOYEE e on to_char(e.EMPLOYEE_NUMBER) = p.SOURCE_USER_ID
 where e.ID is null
   and AUTH_PKG.can_read_sql('ReadTransactions') = 1;
